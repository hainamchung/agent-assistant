#!/usr/bin/env node
'use strict';

/**
 * split-runtime-tiers.js
 *
 * Splits rules/RUNTIME.md into physical tier files:
 *   - rules/RUNTIME-NANO.md   (NANO tier only)
 *   - rules/RUNTIME-MICRO.md  (NANO + MICRO tiers)
 *   - rules/RUNTIME.md        (remains the full file — source of truth)
 *
 * Tier boundaries are defined by HTML comment markers:
 *   <!-- ═══ TIER: NANO ═══ START ═══ -->
 *   <!-- ═══ TIER: NANO ═══ END ═══ -->
 *   <!-- ═══ TIER: MICRO ═══ START ═══ -->
 *   <!-- ═══ TIER: MICRO ═══ END ═══ -->
 *   <!-- ═══ TIER: FULL ═══ START ═══ -->
 *   <!-- ═══ TIER: FULL ═══ END ═══ -->
 *
 * Usage: node scripts/split-runtime-tiers.js
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const RUNTIME_PATH = path.join(PROJECT_ROOT, 'rules', 'RUNTIME.md');
const OUTPUT_DIR = path.join(PROJECT_ROOT, 'rules');

const TIER_START = /^<!--\s*═+\s*TIER:\s*(\w+)\s*═+\s*START\s*═+\s*-->/;
const TIER_END = /^<!--\s*═+\s*TIER:\s*(\w+)\s*═+\s*END\s*═+\s*-->/;

try {
  if (!fs.existsSync(RUNTIME_PATH)) {
    console.error(`❌ RUNTIME.md not found: ${RUNTIME_PATH}`);
    process.exit(1);
  }

  const content = fs.readFileSync(RUNTIME_PATH, 'utf8');
  const lines = content.split('\n');

  // Extract content before first tier marker (preamble: header, loading protocol)
  const preamble = [];
  const tiers = { NANO: [], MICRO: [], FULL: [] };
  let currentTier = null;

  for (const line of lines) {
    const startMatch = line.match(TIER_START);
    const endMatch = line.match(TIER_END);

    if (startMatch) {
      currentTier = startMatch[1].toUpperCase();
      continue; // skip marker line
    }
    if (endMatch) {
      currentTier = null;
      continue; // skip marker line
    }

    if (currentTier && tiers[currentTier] !== undefined) {
      tiers[currentTier].push(line);
    } else if (!currentTier && Object.values(tiers).every(t => t.length === 0)) {
      // Before any tier starts = preamble
      preamble.push(line);
    } else if (!currentTier) {
      // Between tiers or after all tiers — skip (just marker gaps)
    }
  }

  // Validate we found content in each tier
  for (const [name, content] of Object.entries(tiers)) {
    if (content.length === 0) {
      console.error(`⚠️  Warning: Tier ${name} is empty — check tier markers in RUNTIME.md`);
    }
  }

  // Build tier files
  const header = `<!-- Auto-generated by split-runtime-tiers.js — DO NOT EDIT -->\n<!-- Source: rules/RUNTIME.md — edit the source file, then re-run this script -->\n`;

  // NANO = preamble + NANO tier
  const nanoContent = header + preamble.join('\n') + '\n' + tiers.NANO.join('\n') + '\n';

  // MICRO = preamble + NANO + MICRO tiers
  const microContent = header + preamble.join('\n') + '\n' + tiers.NANO.join('\n') + '\n' + tiers.MICRO.join('\n') + '\n';

  const nanoPath = path.join(OUTPUT_DIR, 'RUNTIME-NANO.md');
  const microPath = path.join(OUTPUT_DIR, 'RUNTIME-MICRO.md');

  fs.writeFileSync(nanoPath, nanoContent, 'utf8');
  fs.writeFileSync(microPath, microContent, 'utf8');

  // Word counts
  const nanoWords = nanoContent.split(/\s+/).filter(Boolean).length;
  const microWords = microContent.split(/\s+/).filter(Boolean).length;
  const fullWords = content.split(/\s+/).filter(Boolean).length;

  console.log(`✅ Tier files generated:`);
  console.log(`   • RUNTIME-NANO.md  — ${nanoWords} words (NANO only)`);
  console.log(`   • RUNTIME-MICRO.md — ${microWords} words (NANO + MICRO)`);
  console.log(`   • RUNTIME.md       — ${fullWords} words (full, unchanged)`);
} catch (err) {
  console.error(`❌ Tier splitting failed: ${err.message}`);
  process.exit(1);
}
